"""Generate the female sex rules (data/modifiers/sex_female.yaml).

Usage:  python tools/build_sex_rules.py        (run from the repository root)

Inputs, all inside the repository:
  * data/validation/ansur2_female.yaml  female ANSUR II statistics (built from the raw CSV)
  * data/values/*.yaml                  the male baseline
  * the ICRP 89 female/male pairs below, read from two secondary papers (see sources.yaml)

Each rule is a ratio: female value = male value * ratio. Each ANSUR rule is classified as
'scaling' (size alone explains it) or 'anatomical' (a shape difference) by humansim.validation.

IMPORTANT: the ANSUR rules are CALIBRATED to the ANSUR female means, so a derived female
reproduces those means by construction. That is a consistency check, not independent validation.
"""

from __future__ import annotations

from pathlib import Path

from humansim import Registry
from humansim.validation import load_validation, scaling_analysis

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "humansim" / "data" / "modifiers" / "sex_female.yaml"

# (parameter id, female value, male value, source id, note). Values are for the ICRP 89
# reference female (60 kg) and male (73 kg), read via secondary papers.
ICRP_PAIRS = [
    ("hematocrit", 0.42, 0.45, "pmc8646028",
     "Female 0.42 and male 0.45 as quoted in a model-parameter table."),
    ("cardiac_output", 5.9, 6.5, "pmc8646028",
     "ICRP 89 reference female 5.9 L/min and male 6.5 L/min, quoted in the same table."),
    ("blood_volume", 3.9, 5.3, "pmc6343858",
     "ICRP 89 section 7.4: 3900 cm^3 female and 5300 cm^3 male."),
]
ICRP_CAVEAT = (" The ratio compares a 60 kg female with a 73 kg male, so it includes body-size "
               "differences. Phase 3 will separate size scaling from sex effects.")

# Assumed to have no sex difference. Not sourced; stated so the model does not leave them empty.
NEUTRAL = ["core_temperature", "sao2", "pao2"]


def q(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', "'") + '"'


def main() -> None:
    reg = Registry.load()
    doc = load_validation("ansur2_female")
    lines = [
        "# Female sex rules: female value = male value * ratio. Generated by tools/build_sex_rules.py;",
        "# edit that script, not this file. ANSUR II rules are calibrated to the ANSUR II female means",
        "# (a consistency check, not independent validation).",
        "modifiers:",
    ]
    n_scaling = n_anat = 0
    for row in scaling_analysis(doc, reg):
        pid = row["id"]
        ratio = round(row["ratio"], 5)
        dev = row["deviation"]
        note = (f"ANSUR II female/male mean ratio {ratio:.4f}. Size alone predicts "
                f"{row['expected']:.4f} (deviation {dev:+.1%}); classified {row['type']}.")
        if row["type"] == "scaling":
            n_scaling += 1
        else:
            n_anat += 1
        lines.append(
            f"  - {{id: sex_female_{pid}, stage: sex, op: ratio, effects: {{{pid}: {ratio}}}, "
            f"when: {{sex: female}}, status: referenced, source_ref: ansur2, "
            f"rule_type: {row['type']}, note: {q(note)}}}")

    for pid, f, m, src, note in ICRP_PAIRS:
        ratio = round(f / m, 5)
        lines.append(
            f"  - {{id: sex_female_{pid}, stage: sex, op: ratio, effects: {{{pid}: {ratio}}}, "
            f"when: {{sex: female}}, status: referenced, source_ref: {src}, "
            f"rule_type: physiological, note: {q(note + ICRP_CAVEAT)}}}")

    for pid in NEUTRAL:
        lines.append(
            f"  - {{id: sex_female_{pid}, stage: sex, op: ratio, effects: {{{pid}: 1.0}}, "
            f"when: {{sex: female}}, status: unsourced, rule_type: assumed_neutral, "
            f"note: \"Assumed to have no sex difference. Not sourced.\"}}")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {n_scaling} scaling, {n_anat} anatomical, "
          f"{len(ICRP_PAIRS)} physiological, {len(NEUTRAL)} assumed neutral")


if __name__ == "__main__":
    main()
