"""Build data/values/hormones.yaml from published reference intervals.

Usage:  python tools/build_hormone_data.py        (run from the repository root)

Every number in the INTERVALS table below is a published laboratory reference interval, copied from
the page named in `src` (see data/sources/sources.yaml). The registry needs one representative value
per sex and cycle phase, and an interval is not a mean, so the stored value is the interval's
**midpoint**: geometric when both bounds are above zero (hormone levels are roughly lognormal, so the
geometric midpoint approximates the median), arithmetic when the lower bound is zero or "<x". The
note on every value says so, and it is never a measured mean. The interval itself is stored as the
reference range, so edits outside it are flagged.
Age keys: "adult" for men and for women where the source gives one range; "adult:<phase>" for women
(follicular, midcycle, luteal, postmenopausal).
"""

