"""Build data/genetics/gene_index.yaml from an HGNC complete-set TSV.

Usage:  python tools/import_hgnc.py hgnc_complete_set.txt [--out PATH] [--protein-coding-only]

Download the file yourself from https://www.genenames.org/download/archive/ (the "complete set" TSV).
This tool only reads it; the build environment this was written in could not reach genenames.org, so it
has been tested on a small file in the same column layout, NOT on the real download. It looks columns up
by header name (symbol, name, locus_group, location, status) and stops with a clear message if one is
missing. Only genes with status "Approved" are kept. The result is an index of valid symbols; it carries
no effects. Effects live in the catalogue (measured or hypothetical).
"""

from __future__ import annotations

import argparse
import csv
import sys
from pathlib import Path

import yaml

DEFAULT_OUT = Path(__file__).resolve().parent.parent / "humansim" / "data" / "genetics" / "gene_index.yaml"
REQUIRED = ("symbol", "name", "locus_group", "location", "status")


def read_hgnc(path: Path, protein_coding_only: bool = False) -> list[dict]:
    with path.open(encoding="utf-8", newline="") as fh:
        rd = csv.DictReader(fh, delimiter="\t")
        missing = [c for c in REQUIRED if c not in (rd.fieldnames or [])]
        if missing:
            raise SystemExit(f"{path}: missing column(s) {missing}; found {rd.fieldnames}")
        genes = []
        for row in rd:
            if row["status"] != "Approved":
                continue
            if protein_coding_only and row["locus_group"] != "protein-coding gene":
                continue
            genes.append({"symbol": row["symbol"], "name": row["name"], "locus_group": row["locus_group"],
                          "location": row["location"]})
    return sorted(genes, key=lambda g: g["symbol"])


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("tsv", type=Path)
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    ap.add_argument("--protein-coding-only", action="store_true")
    a = ap.parse_args(argv)
    genes = read_hgnc(a.tsv, a.protein_coding_only)
    a.out.write_text("# Generated by tools/import_hgnc.py from an HGNC download. Symbols only; no effects.\n"
                     + yaml.safe_dump({"genes": genes}, sort_keys=False, allow_unicode=True), encoding="utf-8")
    print(f"{len(genes)} genes written to {a.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
