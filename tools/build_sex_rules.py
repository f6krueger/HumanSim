"""Generate the female sex rules (data/modifiers/sex_female.yaml).

Usage:  python tools/build_sex_rules.py        (run from the repository root)

Inputs, all inside the repository:
  * data/values/*.yaml                  male AND female stored values (the source of every ratio)
  * data/validation/ansur2_female.yaml  used to classify ANSUR ratios as scaling or anatomical

Each rule records the relationship female = male * ratio for a parameter that has both values
stored. The rule is used in BOTH directions, and only to fill in a sex whose value is not stored:
female from male by multiplying, male from female by dividing. A stored value always wins, so for
the parameters below the rule is a documented relationship, not a calculation step.

IMPORTANT: the ratios are computed from the stored pairs, so they agree with them by construction.
"""

from __future__ import annotations

from pathlib import Path

from humansim import Registry
from humansim.validation import load_validation, scaling_analysis

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "humansim" / "data" / "modifiers" / "sex_female.yaml"


# Assumed to have no sex difference. Not sourced; stated so the model does not leave them empty.
NEUTRAL = ["core_temperature", "sao2", "pao2", "muscle_density"]

ICRP_CAVEAT = (" Compares an ICRP 89 reference female (60 kg) with a reference male (73 kg), so the ratio "
               "includes body-size differences. Phase 3 separates size scaling from sex effects.")


def q(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', "'") + '"'


def main() -> None:
    reg = Registry.load()
    doc = load_validation("ansur2_female")
    lines = [
        "# Sex rules: female value = male value * ratio, usable in both directions. Generated by",
        "# tools/build_sex_rules.py from the stored male/female pairs; edit that script, not this file.",
        "modifiers:",
    ]
    counts = {}
    analysis = {r["id"]: r for r in scaling_analysis(doc, reg)}
    for p in reg:
        m, f = p.baseline("male", "adult"), p.baseline("female", "adult")
        if p.kind == "derived" or m is None or f is None:
            continue
        ratio = round(f / m, 5)
        if p.id in analysis:
            row = analysis[p.id]
            rtype = row["type"]
            note = (f"Female/male ratio {ratio:.4f} (ANSUR II). Size alone predicts "
                    f"{row['expected']:.4f} (deviation {row['deviation']:+.1%}); classified {rtype}.")
            if row["expected"] is None:
                note = f"Female/male ratio {ratio:.4f} (ANSUR II); no size-only prediction for this unit."
            src = "ansur2"
        else:
            rtype = "physiological"
            note = f"Female/male ratio {ratio:.4f} from the stored pair." + ICRP_CAVEAT
            src = p.source_ref
        status = "referenced" if src else "unsourced"
        counts[rtype] = counts.get(rtype, 0) + 1
        lines.append(
            f"  - {{id: sex_female_{p.id}, stage: sex, op: ratio, effects: {{{p.id}: {ratio}}}, "
            f"when: {{sex: female}}, status: {status}, source_ref: {src or 'null'}, "
            f"rule_type: {rtype}, note: {q(note)}}}")

    for pid in NEUTRAL:
        if reg[pid].baseline("female", "adult") is not None:
            continue  # a stored female value makes a neutral rule redundant (and a duplicate)
        counts["assumed_neutral"] = counts.get("assumed_neutral", 0) + 1
        lines.append(
            f"  - {{id: sex_female_{pid}, stage: sex, op: ratio, effects: {{{pid}: 1.0}}, "
            f"when: {{sex: female}}, status: unsourced, rule_type: assumed_neutral, "
            f"note: \"Assumed to have no sex difference. Not sourced.\"}}")

    hct = reg["hematocrit"]
    hb_ratio = round(hct.baseline("female", "adult") / hct.baseline("male", "adult"), 5)
    counts["physiological"] = counts.get("physiological", 0) + 1
    lines.append(
        f"  - {{id: sex_female_hemoglobin, stage: sex, op: ratio, effects: {{hemoglobin: {hb_ratio}}}, "
        f"when: {{sex: female}}, status: unsourced, rule_type: physiological, "
        f"note: \"Haemoglobin taken in proportion to the haematocrit ratio (assumes the same mean "
        f"corpuscular haemoglobin concentration in both sexes). Not sourced.\"}}")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {counts}")


if __name__ == "__main__":
    main()
