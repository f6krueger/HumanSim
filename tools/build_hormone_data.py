def q(t: str) -> str:
    return '"' + t.replace('"', "'") + '"'


def midpoint(lo: float, hi: float, lo_is_bound: bool) -> tuple[float, str]:
    if lo > 0 and not lo_is_bound:
        return math.sqrt(lo * hi), "geometric"
    return (lo + hi) / 2.0, "arithmetic"


def main() -> None:
    lines = ["group: hormones", "description: >",
             "  Hormone reference values. Each value is the MIDPOINT of a published laboratory reference interval",
             "  (not a measured mean); the interval is the reference range. Generated by tools/build_hormone_data.py;",
             "  edit that script, not this file.", "parameters:"]
    for pid, (name, unit, rows, note) in INTERVALS.items():
        values = {"male": {}, "female": {}}
        ranges = {}
        srcs = set()
        notes = []
        for sex, key, lo, hi, src, lo_bound in rows:
            mid, kind = midpoint(lo, hi, lo_bound)
            values[sex][key] = round(mid, 4)
            rk = sex if key == "adult" else f"{sex}:{key.split(':')[1]}"
            ranges[rk] = (lo, hi)
            srcs.add(src)
            notes.append(f"{rk} {kind} midpoint of {lo}-{hi}")
        if len(srcs) != 1:
            raise SystemExit(f"{pid}: one source per parameter expected")
        vals = ", ".join(f"{s}: {{" + ", ".join(f"{k}: {v}" for k, v in d.items()) + "}" for s, d in values.items() if d)
        rngs = ", ".join(f"{('\"' + k + '\"') if ':' in k else k}: [{lo}, {hi}]" for k, (lo, hi) in ranges.items())
        full = (note + " " if note else "") + "Stored value is the midpoint of the published interval: " + "; ".join(notes) + "."
        lines.append(f"  - {{id: {pid}, name: {q(name)}, unit: {q(unit) if '/' in unit else unit}, kind: dynamic, "
                     f"values: {{{vals}}}, status: referenced, source_ref: {srcs.pop()}, ref_range: {{{rngs}}}, "
                     f"range_source_ref: null, note: {q(full)}}}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {len(INTERVALS)} hormone parameters")


if __name__ == "__main__":
    main()
