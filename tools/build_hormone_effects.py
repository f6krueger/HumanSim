"""Build data/modifiers/hormone_effects.yaml.

Usage:  python tools/build_hormone_effects.py        (run from the repository root)

Testosterone and lean mass: Bhasin et al. 2001 (see sources.yaml: bhasin2001). Healthy men aged
18-35 had their own testosterone suppressed and received weekly testosterone enanthate for 20 weeks.
The abstract gives the serum testosterone reached and the fat-free mass change for three dose groups:

    nadir serum testosterone (ng/dL)   542    1345   2370
    fat-free mass change (kg)          +3.4   +5.2   +7.9

The effect is modelled as  change = slope * ln(T / T_reference), the least-squares slope of the
three points against ln(T). Only the SLOPE is used, not the intercept: the concentrations are
troughs of weekly injections and the abstract does not give each group's baseline, so the absolute
level is not transferable. Fat-free mass is mapped to skeletal muscle mass (an assumption: most of the
change in fat-free mass in this setting is muscle, but water and organ mass also contribute).
Valid only over the studied concentrations (542-2370 ng/dL); outside it the effect is flagged.
"""

from __future__ import annotations

import math
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "humansim" / "data" / "modifiers" / "hormone_effects.yaml"
POINTS = [(542.0, 3.4), (1345.0, 5.2), (2370.0, 7.9)]


def slope() -> float:
    xs = [math.log(t) for t, _ in POINTS]
    ys = [y for _, y in POINTS]
    xb, yb = sum(xs) / len(xs), sum(ys) / len(ys)
    return sum((x - xb) * (y - yb) for x, y in zip(xs, ys)) / sum((x - xb) ** 2 for x in xs)


def main() -> None:
    b = round(slope(), 4)
    note = (f"Bhasin 2001: fat-free mass change {b} kg per unit of ln(testosterone) from three dose groups "
            "(542, 1345, 2370 ng/dL nadir; +3.4, +5.2, +7.9 kg at 20 weeks). Slope only; the baseline is not "
            "transferable. Fat-free mass is mapped to skeletal muscle mass (assumed). A sustained-level effect "
            "after about 20 weeks, men 18-35 whose own production was suppressed.")
    OUT.write_text(
        "# Hormone effects. Generated by tools/build_hormone_effects.py; edit that script, not this file.\n"
        "modifiers:\n"
        f"  - {{id: testosterone_skeletal_muscle, stage: hormone, op: log_slope, driver: testosterone_total, "
        f"effects: {{skeletal_muscle_mass: {b}}}, when: {{sex: male, \"hormone:testosterone_total\": true}}, "
        f"validity: [542, 2370], status: referenced, source_ref: bhasin2001, rule_type: hormonal, "
        f"note: \"{note}\"}}\n", encoding="utf-8")
    print(f"slope {b} kg per ln unit")


if __name__ == "__main__":
    main()
